class TestCrossSessionContinuityE2E:
    """P1: Cross-session continuity — save→exit→restart→load full workflow.

    Gap: existing test_cross_scenario_continuity_e2e.py::test_save_during_battle_then_load
    uses save→load in the **same process**. This test validates **true process
    restart** (subprocess-based simulation).

    User journey:
      1. Start game → progress to battle
      2. Save game (quick_save)
      3. Exit game (terminate process)
      4. Restart game (new process)
      5. Load game (quick_load)
      6. Continue battle (verify state continuity)

    Success criteria:
      - Save file written successfully
      - Process restart succeeds
      - Load restores exact game state (unit positions, HP, ammo, morale)
      - Game loop continues without crashes after load
    """

    @pytest.mark.slow
    def test_cross_session_save_exit_restart_load(self, tmp_path: Path) -> None:
        """Save→exit→restart→load: full cross-session continuity.

        Uses subprocess to simulate true process restart. The first subprocess
        creates a save file; the second subprocess loads it and verifies state.
        """
        save_dir = tmp_path / "saves"
        save_dir.mkdir(parents=True, exist_ok=True)
        save_file = save_dir / "cross_session_test.json"

        # Phase 1: Create save file in subprocess 1
        phase1_script = f"""
import os
os.environ["SDL_VIDEODRIVER"] = "dummy"
os.environ["SDL_AUDIODRIVER"] = "dummy"
os.environ["SDL_JOYSTICK_DRIVER"] = "dummy"

import pygame
pygame.init()
screen = pygame.display.set_mode((1280, 720))

from pathlib import Path
from conftest import GameLoopFactory
from pycc2.infrastructure.save_system import SecureSaveManager

factory = GameLoopFactory(screen)
save_mgr = SecureSaveManager(save_dir=Path("{save_dir}"), hmac_key="{_STABLE_HMAC_KEY}")

# Run a few ticks to establish state
factory.run_ticks(5)

# Quick save
state_data, meta_data = factory.game_loop._save_controller.export_state()
status = save_mgr.save(Path("{save_file}"), state_data, meta_data)
assert status == SaveSlotStatus.VALID, f"save failed: {{status}}"

# Record initial unit state for later verification
units = factory.game_loop.state.units
with open("{tmp_path}/unit_snapshot.json", "w") as f:
    import json
    json.dump({{
        "count": len(units),
        "positions": {{u.id: {{
            "x": u.position.tile_coord.x,
            "y": u.position.tile_coord.y,
            "hp": u.health.hp,
            "ammo": u.weapon.ammo_remaining if u.weapon else 0
        }} for u in units}}
    }}, f)

factory.shutdown()
pygame.quit()
print("PHASE1_SUCCESS")
"""

        result1 = subprocess.run(
            [sys.executable, "-c", phase1_script],
            cwd=Path(__file__).parent.parent.parent,  # PyCC2 repo root
            capture_output=True,
            text=True,
            timeout=60,
        )

        assert "PHASE1_SUCCESS" in result1.stdout, f"Phase 1 failed:\n{result1.stderr}"
        assert save_file.exists(), "save file not created"

        # Phase 2: Load save file in subprocess 2 (simulates restart)
        phase2_script = f"""
import os
os.environ["SDL_VIDEODRIVER"] = "dummy"
os.environ["SDL_AUDIODRIVER"] = "dummy"
os.environ["SDL_JOYSTICK_DRIVER"] = "dummy"

import pygame
pygame.init()
screen = pygame.display.set_mode((1280, 720))

import json
from pathlib import Path
from conftest import GameLoopFactory
from pycc2.infrastructure.save_system import SecureSaveManager

factory = GameLoopFactory(screen)
save_mgr = SecureSaveManager(save_dir=Path("{save_dir}"), hmac_key="{_STABLE_HMAC_KEY}")

# Quick load
state_data, meta_data, status = save_mgr.load(Path("{save_file}"))
assert status == SaveSlotStatus.VALID, f"load failed: {{status}}"
assert state_data is not None, "loaded state_data is None"

# Import state
factory.game_loop._save_controller.import_state(state_data, meta_data)

# Verify unit state matches phase 1
units = factory.game_loop.state.units
with open("{tmp_path}/unit_snapshot.json", "r") as f:
    snapshot = json.load(f)

assert len(units) == snapshot["count"], "unit count mismatch after load"

for u in units:
    orig = snapshot["positions"][u.id]
    assert u.position.tile_coord.x == orig["x"], f"unit {{u.id}} x mismatch"
    assert u.position.tile_coord.y == orig["y"], f"unit {{u.id}} y mismatch"
    assert u.health.hp == orig["hp"], f"unit {{u.id}} hp mismatch"
    if u.weapon:
        assert u.weapon.ammo_remaining == orig["ammo"], f"unit {{u.id}} ammo mismatch"

# Run a few more ticks to verify game loop continues
factory.run_ticks(3)

factory.shutdown()
pygame.quit()
print("PHASE2_SUCCESS")
"""

        result2 = subprocess.run(
            [sys.executable, "-c", phase2_script],
            cwd=Path(__file__).parent.parent.parent,
            capture_output=True,
            text=True,
            timeout=60,
        )

        assert "PHASE2_SUCCESS" in result2.stdout, f"Phase 2 failed:\n{result2.stderr}"


