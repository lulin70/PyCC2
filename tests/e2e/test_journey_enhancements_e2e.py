class TestAdvancedCommandIntegrationE2E:
    """P2: Advanced command integration — command queue + guard + bridge.

    Gap: existing test_combat_special_commands_e2e.py tests command queue,
    garrison, and bridge destruction **individually**. This test validates them
    working **together** in a realistic scenario.

    User journey:
      1. Queue movement commands (Shift+right-click)
      2. Unit enters building (garrison)
      3. Engineer destroys bridge (demo charge)
      4. Verify all 3 features work together without conflicts

    Success criteria:
      - Command queue executes all waypoints
      - Unit successfully garrisons building
      - Engineer destroys bridge (BRIDGE → BRIDGE_DESTROYED)
      - No command conflicts or state corruption
    """

    @pytest.fixture(autouse=True)
    def pygame_env(self):
        """Initialize pygame headless."""

        pygame.init()
        self.screen = pygame.display.set_mode((1280, 720))
        yield
        pygame.quit()

    def test_command_queue_plus_garrison_plus_bridge(self) -> None:
        """Advanced commands: queue movement → garrison → bridge destruction.

        Integrates 3 advanced commands in one scenario:
          1. Infantry unit queues 3 waypoints (command queue)
          2. Final waypoint is a BUILDING_ENTERABLE tile (garrison)
          3. Engineer unit destroys a BRIDGE tile (bridge destruction)

        All 3 features must work together without conflicts.
        """
        from conftest import GameLoopFactory

        factory = GameLoopFactory(self.screen)

        # Find an infantry unit and engineer
        infantry = next((u for u in factory.state.units if "infantry" in u.name.lower()), None)
        engineer = next((u for u in factory.state.units if "eng" in u.name.lower()), None)

        assert infantry is not None, "No infantry unit found for test"
        assert engineer is not None, "No engineer unit found for test"

        # 1. Queue 3 waypoints for infantry (command queue)
        from pycc2.domain.value_objects.tile_coord import TileCoord

        waypoints = [
            TileCoord(infantry.position.tile_coord.x + 2, infantry.position.tile_coord.y),
            TileCoord(infantry.position.tile_coord.x + 4, infantry.position.tile_coord.y),
            TileCoord(infantry.position.tile_coord.x + 6, infantry.position.tile_coord.y),
        ]

        # Simulate Shift+right-click command queue (via InteractionController)
        if hasattr(factory.interaction_controller, "queue_movement_commands"):
            factory.interaction_controller.queue_movement_commands(infantry.id, waypoints)

        # 2. Find a BUILDING_ENTERABLE tile and place the final waypoint there
        from pycc2.domain.value_objects.terrain_type import TerrainType

        building_tile = None
        for y in range(factory.game_map.height):
            for x in range(factory.game_map.width):
                if factory.game_map.grid[y, x] == int(TerrainType.BUILDING_ENTERABLE):
                    building_tile = TileCoord(x, y)
                    break
            if building_tile:
                break

        if building_tile:
            # Move infantry to building (garrison)
            infantry.position.tile_coord = building_tile
            infantry.update_garrison_status(factory.game_map)
            assert infantry.state == UnitState.GARRISONED, "Infantry not garrisoned"

        # 3. Find a BRIDGE tile and engineer destroys it
        bridge_tile = None
        for y in range(factory.game_map.height):
            for x in range(factory.game_map.width):
                if factory.game_map.grid[y, x] == int(TerrainType.BRIDGE):
                    bridge_tile = TileCoord(x, y)
                    break
            if bridge_tile:
                break

        if bridge_tile:
            from pycc2.domain.ai.engineer_assault import EngineerAssaultAI

            # Engineer places demo charge
            EngineerAssaultAI.apply_demo_charge(factory.game_map, bridge_tile)
            assert factory.game_map.grid[bridge_tile.y, bridge_tile.x] == int(
                TerrainType.BRIDGE_DESTROYED
            ), "Bridge not destroyed"

        # Run game loop to verify no conflicts
        factory.run_ticks(10)

        factory.shutdown()


