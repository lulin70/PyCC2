class TestDockerCleanInstallE2E:
    """P1: First-time install in pristine Docker environment.

    Gap: existing test_installation_startup_e2e.py runs in the local development
    environment with pre-existing dependencies. This test validates a **Docker
    clean environment** (no cached dependencies, no user config).

    User journey:
      1. Build Docker image from Dockerfile
      2. Run container with no mounted volumes
      3. Start game in headless mode
      4. Verify all subsystems initialize
      5. Run basic game loop

    Success criteria:
      - Docker image builds without errors
      - Game starts in clean environment (no config files)
      - All subsystems initialize (renderer, AI, event bus, sound)
      - Game loop runs for 10 ticks without crashes
    """

    @pytest.mark.slow
    @pytest.mark.skipif(
        os.environ.get("SKIP_DOCKER_TESTS", "0") == "1",
        reason="Docker tests skipped (SKIP_DOCKER_TESTS=1)",
    )
    def test_docker_clean_environment_startup(self) -> None:
        """Docker clean install: pristine environment game startup.

        Builds a temporary Docker image, runs it with no volumes, and verifies
        the game initializes all subsystems in a clean environment.
        """
        repo_root = Path(__file__).parent.parent.parent
        dockerfile = repo_root / "Dockerfile"

        if not dockerfile.exists():
            pytest.skip("Dockerfile not found — cannot run Docker clean install test")

        # Build Docker image
        build_result = subprocess.run(
            ["docker", "build", "-t", "pycc2-e2e-test:latest", "."],
            cwd=repo_root,
            capture_output=True,
            text=True,
            timeout=600,  # 10 minutes for image build
        )

        if build_result.returncode != 0:
            pytest.skip(f"Docker build failed:\n{build_result.stderr}")

        # Run container with clean environment test script
        test_script = """
import os
os.environ["SDL_VIDEODRIVER"] = "dummy"
os.environ["SDL_AUDIODRIVER"] = "dummy"
os.environ["SDL_JOYSTICK_DRIVER"] = "dummy"

import pygame
pygame.init()
screen = pygame.display.set_mode((1280, 720))

from conftest import GameLoopFactory

# Initialize game in clean environment
factory = GameLoopFactory(screen)

# Verify subsystems
assert factory.game_loop is not None, "GameLoop not initialized"
assert factory.renderer is not None, "Renderer not initialized"
assert factory.ai_service is not None, "AI service not initialized"
assert factory.event_bus is not None, "Event bus not initialized"
assert factory.sound_system is not None, "Sound system not initialized"

# Run game loop
factory.run_ticks(10)

factory.shutdown()
pygame.quit()
print("DOCKER_CLEAN_INSTALL_SUCCESS")
"""

        run_result = subprocess.run(
            [
                "docker",
                "run",
                "--rm",
                "-e",
                "SDL_VIDEODRIVER=dummy",
                "-e",
                "SDL_AUDIODRIVER=dummy",
                "-e",
                "SDL_JOYSTICK_DRIVER=dummy",
                "pycc2-e2e-test:latest",
                "python3",
                "-c",
                test_script,
            ],
            capture_output=True,
            text=True,
            timeout=120,
        )

        assert "DOCKER_CLEAN_INSTALL_SUCCESS" in run_result.stdout, (
            f"Docker clean install test failed:\n{run_result.stderr}"
        )


