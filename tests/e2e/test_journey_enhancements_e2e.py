class TestErrorRecoveryJourneyE2E:
    """P2: Error recovery journey — error→save→load full workflow.

    Gap: existing test_error_recovery_e2e.py tests individual error types
    (AI tick failure, render failure, etc.) but not the **full recovery workflow**:
    error occurs → save game → load game → continue playing.

    User journey:
      1. Game running normally
      2. Error occurs (AI tick failure)
      3. Game saves state (quick_save during error handling)
      4. Game loads state (quick_load)
      5. Game continues without crashes

    Success criteria:
      - Error logged but game does not crash
      - Save succeeds during error condition
      - Load restores valid state
      - Game loop continues after recovery
    """

    @pytest.fixture(autouse=True)
    def pygame_env(self):
        """Initialize pygame headless."""

        pygame.init()
        self.screen = pygame.display.set_mode((1280, 720))
        yield
        pygame.quit()

    def test_error_then_save_then_load_recovery(self, tmp_path: Path, monkeypatch) -> None:
        """Error→save→load: full error recovery workflow.

        Simulates an AI tick error, saves game state during the error, loads
        the save, and verifies game continues.
        """
        from conftest import GameLoopFactory

        save_dir = tmp_path / "saves"
        save_dir.mkdir(parents=True, exist_ok=True)
        save_file = save_dir / "error_recovery_test.json"

        factory = GameLoopFactory(self.screen)
        save_mgr = SecureSaveManager(save_dir=save_dir, hmac_key=_STABLE_HMAC_KEY)

        # Inject AI tick error (monkeypatch)
        def _failing_ai_tick(*args, **kwargs):
            raise RuntimeError("Simulated AI tick error")

        monkeypatch.setattr(factory.ai_service, "tick", _failing_ai_tick)

        # Run ticks — error should be logged but game continues
        errors = factory.run_ticks(5)
        assert len(errors) > 0, "expected AI tick errors to be logged"

        # Save game during error condition
        state_data, meta_data = factory.game_loop._save_controller.export_state()
        status = save_mgr.save(save_file, state_data, meta_data)
        assert status == SaveSlotStatus.VALID, f"save failed during error: {status}"

        # Restore AI service (remove monkeypatch)
        monkeypatch.undo()

        # Load game
        loaded_state, loaded_meta, load_status = save_mgr.load(save_file)
        assert load_status == SaveSlotStatus.VALID, f"load failed: {load_status}"
        factory.game_loop._save_controller.import_state(loaded_state, loaded_meta)

        # Continue game loop after recovery
        factory.run_ticks(5)

        factory.shutdown()


